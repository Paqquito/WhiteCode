// Implements: SPEC-BLD-001 (steps 1-2: identity validation and constant generation), SPEC-CAD-002 (§ 5.3 steps 1-4)
// Resolves the identity file and the model catalogue, then writes the build-time constants module.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { resolveIdentityText } from "../src/identity/resolver";
import { ModelCatalog } from "../src/providers/catalog";

const root = resolve(import.meta.dir, "..");

function arg(name: string, fallback: string): string {
  const i = process.argv.indexOf(name);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1]! : fallback;
}

const identityPath = resolve(root, arg("--identity", "identity/dev.identity.json"));
const modelsPath = resolve(root, arg("--models", "identity/dev.models.json"));
const outPath = join(root, "src/identity/generated/build-data.ts");

const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8")) as { version: string };
const result = resolveIdentityText(readFileSync(identityPath, "utf8"), { version: pkg.version, strict: true });
for (const issue of result.issues) console.error(`[${issue.code}] ${issue.message}`);
if (!result.identity) process.exit(2);

const catalogData: unknown = JSON.parse(readFileSync(modelsPath, "utf8"));
new ModelCatalog(catalogData); // throws on an invalid catalogue

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(
  outPath,
  [
    "// Supports: SPEC-CAD-002 (EF-15 identity manifest), SPEC-API-006 (embedded catalogue)",
    "// Generated by scripts/generate.ts from the identity file of the build. Do not edit, do not commit.",
    'import type { ResolvedIdentity } from "../resolver";',
    "",
    `export const RESOLVED_IDENTITY: ResolvedIdentity = ${JSON.stringify(result.identity, null, 2)};`,
    "",
    `export const MODEL_CATALOG_DATA: unknown = ${JSON.stringify(catalogData, null, 2)};`,
    "",
  ].join("\n"),
);
console.error(`identity ${result.identity.hash.slice(0, 12)} -> ${outPath}`);
